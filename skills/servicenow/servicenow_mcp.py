def main():
    """CLI entry point for quick tests."""
    import argparse
    
    parser = argparse.ArgumentParser(description="ServiceNow MCP Integration")
    parser.add_argument("action", choices=["health", "emails", "create-email", "create-incident"])
    parser.add_argument("--limit", type=int, default=5)
    parser.add_argument("--recipient", default="test@example.com")
    parser.add_argument("--subject", default="Test Subject")
    parser.add_argument("--body", default="Test body content")
    parser.add_argument("--description", default="Test incident")
    
    args = parser.parse_args()
    
    mcp = ServiceNowMCP()
    
    if args.action == "health":
        result = mcp.health_check()
        print(json.dumps(result, indent=2))
        
    elif args.action == "emails":
        emails = mcp.get_emails(limit=args.limit)
        print(f"Found {len(emails)} emails:")
        for e in emails:
            print(f"  - {e.get('sys_id')}: {e.get('subject', 'N/A')} -> {e.get('recipient', 'N/A')}")
            
    elif args.action == "create-email":
        try:
            result = mcp.create_email(
                recipient=args.recipient,
                subject=args.subject,
                body=args.body
            )
            print(f"Created email: {result.get('sys_id')}")
        except RecordExistsError as e:
            print(f"Duplicate detected: {e}")
        except WatermarkDetectedError as e:
            print(f"Watermark detected: {e}")
            
    elif args.action == "create-incident":
        try:
            result = mcp.create_incident(
                short_description=args.description,
                caller="admin"
            )
            print(f"Created incident: {result.get('number')} ({result.get('sys_id')})")
        except RecordExistsError as e:
            print(f"Duplicate detected: {e}")


if __name__ == "__main__":
    main()
